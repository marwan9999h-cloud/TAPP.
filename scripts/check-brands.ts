interface DecodedPng {
  width: number;
  height: number;
  rgba: Uint8ClampedArray;
}

function paethPredictor(a: number, b: number, c: number): number {
  const p = a + b - c;
  const pa = Math.abs(p - a);
  const pb = Math.abs(p - b);
  const pc = Math.abs(p - c);
  if (pa <= pb && pa <= pc) return a;
  if (pb <= pc) return b;
  return c;
}

/**
 * Pure-Node PNG decoder supporting bit-depth 8 PNG images generated by qrcode (Gray, RGB, Palette, GrayA, RGBA).
 */
function decodePngBuffer(buffer: Buffer): DecodedPng {
  const pngSignature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  assert.ok(buffer.subarray(0, 8).equals(pngSignature), 'Invalid PNG file signature');

  let offset = 8;
  let width = 0;
  let height = 0;
  let bitDepth = 0;
  let colorType = 0;
  let palette: Buffer | null = null;
  const idatChunks: Buffer[] = [];

  while (offset < buffer.length) {
    const length = buffer.readUInt32BE(offset);
    const type = buffer.toString('ascii', offset + 4, offset + 8);
    const data = buffer.subarray(offset + 8, offset + 8 + length);
    offset += 12 + length;

    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      bitDepth = data.readUInt8(8);
      colorType = data.readUInt8(9);
      const interlace = data.readUInt8(12);
      assert.equal(interlace, 0, 'Interlaced PNGs are not supported');
    } else if (type === 'PLTE') {
      palette = data;
    } else if (type === 'IDAT') {
      idatChunks.push(data);
    } else if (type === 'IEND') {
      break;
    }
  }

  assert.ok(width > 0 && height > 0, 'PNG IHDR missing valid dimensions');
  assert.equal(bitDepth, 8, `Unsupported PNG bit depth ${bitDepth}`);

  const channelsByType: Record<number, number> = {
    0: 1,
    2: 3,
    3: 1,
    4: 2,
    6: 4,
  };
  const channels = channelsByType[colorType];
  assert.ok(channels !== undefined, `Unsupported PNG color type ${colorType}`);

  const raw = zlib.inflateSync(Buffer.concat(idatChunks));
  const stride = width * channels;
  const unfiltered = Buffer.alloc(height * stride);

  for (let y = 0; y < height; y++) {
    const rowStart = y * (stride + 1);
    const filterType = raw[rowStart];
    const scanline = raw.subarray(rowStart + 1, rowStart + 1 + stride);
    const outRowOffset = y * stride;

    for (let x = 0; x < stride; x++) {
      const val = scanline[x];
      const left = x >= channels ? unfiltered[outRowOffset + x - channels] : 0;
      const up = y > 0 ? unfiltered[(y - 1) * stride + x] : 0;
      const upLeft =
        y > 0 && x >= channels ? unfiltered[(y - 1) * stride + x - channels] : 0;

      let recon = val;
      if (filterType === 1) recon = (val + left) & 0xff;
      else if (filterType === 2) recon = (val + up) & 0xff;
      else if (filterType === 3) recon = (val + Math.floor((left + up) / 2)) & 0xff;
      else if (filterType === 4) recon = (val + paethPredictor(left, up, upLeft)) & 0xff;
      else if (filterType !== 0) {
        throw new Error(`Unsupported PNG filter type ${filterType}`);
      }
      unfiltered[outRowOffset + x] = recon;
    }
  }

  const rgba = new Uint8ClampedArray(width * height * 4);
  for (let i = 0; i < width * height; i++) {
    const srcIdx = i * channels;
    const dstIdx = i * 4;
    if (colorType === 6) {
      rgba[dstIdx] = unfiltered[srcIdx];
      rgba[dstIdx + 1] = unfiltered[srcIdx + 1];
      rgba[dstIdx + 2] = unfiltered[srcIdx + 2];
      rgba[dstIdx + 3] = unfiltered[srcIdx + 3];
    } else if (colorType === 2) {
      rgba[dstIdx] = unfiltered[srcIdx];
      rgba[dstIdx + 1] = unfiltered[srcIdx + 1];
      rgba[dstIdx + 2] = unfiltered[srcIdx + 2];
      rgba[dstIdx + 3] = 255;
    } else if (colorType === 0) {
      const g = unfiltered[srcIdx];
      rgba[dstIdx] = g;
      rgba[dstIdx + 1] = g;
      rgba[dstIdx + 2] = g;
      rgba[dstIdx + 3] = 255;
    } else if (colorType === 4) {
      const g = unfiltered[srcIdx];
      rgba[dstIdx] = g;
      rgba[dstIdx + 1] = g;
      rgba[dstIdx + 2] = g;
      rgba[dstIdx + 3] = unfiltered[srcIdx + 1];
    } else if (colorType === 3) {
      assert.ok(palette, 'Indexed PNG missing PLTE palette');
      const idx = unfiltered[srcIdx] * 3;
      rgba[dstIdx] = palette[idx];
      rgba[dstIdx + 1] = palette[idx + 1];
      rgba[dstIdx + 2] = palette[idx + 2];
      rgba[dstIdx + 3] = 255;
    }
  }

  return { width, height, rgba };
}

/**
 * Rasterizes the horizontal scanline SVG `<path stroke="...">` produced by `qrcode` into an RGBA pixel grid
 * so jsQR validates the exact vector output geometry.
 */
function rasterizeQrSvgToRgba(svg: string): DecodedPng {
  const viewBoxMatch = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  assert.ok(viewBoxMatch, 'Generated QR SVG missing viewBox');
  const modules = Number(viewBoxMatch[1]);
  assert.equal(Number(viewBoxMatch[2]), modules, 'QR SVG viewBox must be square');
  assert.ok(modules >= 21, `Unexpectedly small QR SVG module dimension: ${modules}`);

  const strokePathMatch = svg.match(/<path[^>]*stroke="[^"]+"[^>]*d="([^"]+)"/);
  assert.ok(strokePathMatch, 'Generated QR SVG missing module stroke path');
  const d = strokePathMatch[1];

  const grid = Array.from({ length: modules }, () => new Uint8Array(modules));
  const tokens = d.match(/[A-Za-z]|-?\d+(?:\.\d+)?/g) ?? [];

  let i = 0;
  let curX = 0;
  let curY = 0;
  let cmd = '';

  while (i < tokens.length) {
    const token = tokens[i];
    if (/^[A-Za-z]$/.test(token)) {
      cmd = token;
      i++;
      if (cmd === 'z' || cmd === 'Z') continue;
    }

    if (cmd === 'M') {
      curX = Number(tokens[i++]);
      curY = Number(tokens[i++]);
      cmd = 'L';
    } else if (cmd === 'm') {
      curX += Number(tokens[i++]);
      curY += Number(tokens[i++]);
      cmd = 'l';
    } else if (cmd === 'h') {
      const len = Number(tokens[i++]);
      const row = Math.floor(curY);
      const startCol = Math.round(curX);
      const endCol = Math.round(curX + len);
      for (let c = Math.min(startCol, endCol); c < Math.max(startCol, endCol); c++) {
        if (row >= 0 && row < modules && c >= 0 && c < modules) {
          grid[row][c] = 1;
        }
      }
      curX += len;
    } else if (cmd === 'H') {
      const targetX = Number(tokens[i++]);
      const row = Math.floor(curY);
      const startCol = Math.round(curX);
      const endCol = Math.round(targetX);
      for (let c = Math.min(startCol, endCol); c < Math.max(startCol, endCol); c++) {
        if (row >= 0 && row < modules && c >= 0 && c < modules) {
          grid[row][c] = 1;
        }
      }
      curX = targetX;
    } else {
      throw new Error(`Unexpected SVG path command "${cmd}" in QR SVG`);
    }
  }

  for (let p = 0; p < modules; p++) {
    assert.equal(grid[0][p], 0, 'Top quiet-zone pixel corrupted');
    assert.equal(grid[modules - 1][p], 0, 'Bottom quiet-zone pixel corrupted');
    assert.equal(grid[p][0], 0, 'Left quiet-zone pixel corrupted');
    assert.equal(grid[p][modules - 1], 0, 'Right quiet-zone pixel corrupted');
  }

  const scale = 12;
  const size = modules * scale;
  const rgba = new Uint8ClampedArray(size * size * 4);
  for (let py = 0; py < size; py++) {
    const my = Math.floor(py / scale);
    for (let px = 0; px < size; px++) {
      const mx = Math.floor(px / scale);
      const isDark = grid[my][mx] === 1;
      const idx = (py * size + px) * 4;
      const val = isDark ? 0 : 255;
      rgba[idx] = val;
      rgba[idx + 1] = val;
      rgba[idx + 2] = val;
      rgba[idx + 3] = 255;
    }
  }

  return { width: size, height: size, rgba };
}

function assertValidExternalUrl(rawUrl: string, label: string): void {
  let parsed: URL;
  try {
    parsed = new URL(rawUrl);
  } catch {
    throw new Error(`Invalid URL for ${label}: ${rawUrl}`);
  }
  assert.ok(
    parsed.protocol === 'https:' || parsed.protocol === 'http:',
    `Unsupported URL protocol for ${label}: ${parsed.protocol}`
  );
  assert.ok(!rawUrl.includes('localhost'), `Localhost leaked into ${label}: ${rawUrl}`);
  assert.ok(!rawUrl.includes('example.com'), `Placeholder URL leaked into ${label}: ${rawUrl}`);
}

function stripTags(htmlFragment: string): string {
  return htmlFragment
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim();
}

